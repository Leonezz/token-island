#!/usr/bin/env bash
#
# Build the Token Island macOS app bundle.
#
#   bash apps/island-macos/scripts/build-app.sh
#
# Output: apps/island-macos/build/TokenIsland.app
# The bundle is a menu-bar-only (LSUIElement) app; run it with `open` or by
# executing Contents/MacOS/TokenIsland directly.

set -euo pipefail

APP_NAME="TokenIsland"
BUNDLE_ID="com.token-island.app"
VERSION="0.1.0"
BUILD_VERSION="1"

ISLAND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "$ISLAND_DIR/../.." && pwd)"
BUILD_DIR="$ISLAND_DIR/build"
APP="$BUILD_DIR/$APP_NAME.app"
CONFIG="release"

echo "==> swift build -c $CONFIG"
# --disable-sandbox: SwiftPM's manifest/plugin sandbox uses sandbox-exec, which
# is unavailable in some restricted/CI environments. It is not needed for a
# dependency-free package.
swift build -c "$CONFIG" --package-path "$ISLAND_DIR" --disable-sandbox
BIN_DIR="$(swift build -c "$CONFIG" --package-path "$ISLAND_DIR" --disable-sandbox --show-bin-path)"
BIN="$BIN_DIR/$APP_NAME"
if [[ ! -x "$BIN" ]]; then
    echo "error: expected binary at $BIN" >&2
    exit 1
fi

echo "==> assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN" "$APP/Contents/MacOS/$APP_NAME"
chmod +x "$APP/Contents/MacOS/$APP_NAME"

# Info.plist (menu-bar app: LSUIElement, no Dock icon).
cp "$ISLAND_DIR/Resources/Info.plist" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleIdentifier $BUNDLE_ID" "$APP/Contents/Info.plist" >/dev/null
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist" >/dev/null
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion $BUILD_VERSION" "$APP/Contents/Info.plist" >/dev/null

# Demo fixture used by `--demo` and by the snapshot renderer when no --fixture
# is passed. Regenerated by the Lead in the repo, so copy it at build time.
FIXTURE="$REPO_ROOT/fixtures/summary.example.json"
if [[ -f "$FIXTURE" ]]; then
    cp "$FIXTURE" "$APP/Contents/Resources/summary.example.json"
    echo "    resources: summary.example.json"
else
    echo "warning: $FIXTURE not found (snapshots will need --fixture)" >&2
fi

# Strip quarantine attributes from the freshly built bundle (ignore failures).
xattr -dr com.apple.quarantine "$APP" 2>/dev/null || true

# Validate the plist so a broken bundle never ships silently.
if ! plutil -lint "$APP/Contents/Info.plist" >/dev/null; then
    echo "error: invalid Info.plist" >&2
    exit 1
fi

echo "==> built: $APP"
echo "    run:   $APP/Contents/MacOS/$APP_NAME --demo"
echo "    snap:  $APP/Contents/MacOS/$APP_NAME --snapshot /tmp/island.png --state expanded --scale 2 --background wallpaper"
echo "    install: bash apps/island-macos/scripts/install.sh"
